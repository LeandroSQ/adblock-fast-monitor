'use strict';
const assert = require('assert');
const fs = require('fs');
const inventory = fs.readFileSync('root/usr/libexec/adblock-fast-monitor-classifier-inventory.uc', 'utf8');
assert.match(inventory, /connection\.call\('service', 'list', \{ name: 'dnsmasq' \}\)/);
assert.match(inventory, /length\(keys\(instances\)\) != 1/);
assert.match(inventory, /type\(instance\?\.pid\) != 'number'/);
assert.match(inventory, /command\[index\] == '-C'/);
assert.match(inventory, /--conf-file.*--conf-dir.*--addn-hosts.*--servers-file/s);
assert.match(inventory, /\^\(conf-file\|conf-dir\|addn-hosts\|servers-file\)=/);
console.log('classifier inventory contracts passed');
